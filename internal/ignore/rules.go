package ignore

import (
	"os"
	"strings"
)

// UserRules represents the user-managed ignore rules stored in ws.json under
// ignore_rules. .megaignore is a generated output.
type UserRules struct {
	Schema           int         `json:"schema"`
	Exclude          []RuleEntry `json:"exclude"`
	Include          []RuleEntry `json:"include"`
	SuppressDefaults []string    `json:"suppress_defaults"`
}

// RuleEntry is a single user-defined rule with an optional note.
type RuleEntry struct {
	Pattern string `json:"pattern"`
	Note    string `json:"note,omitempty"`
}

const UserRulesSchema = 1

// DefaultUserRules returns an empty UserRules with the current schema.
func DefaultUserRules() UserRules {
	return UserRules{
		Schema:           UserRulesSchema,
		Exclude:          []RuleEntry{},
		Include:          []RuleEntry{},
		SuppressDefaults: []string{},
	}
}

// builtinExcludes is the built-in exclude template minus suppress_defaults,
// each rule tagged SourceBuiltin.
func builtinExcludes(u UserRules) []Rule {
	off := make(map[string]bool, len(u.SuppressDefaults))
	for _, s := range u.SuppressDefaults {
		off[s] = true
	}
	var out []Rule
	for _, r := range defaultExcludeRules {
		if off[r.Pattern] {
			continue
		}
		r.Source = SourceBuiltin
		out = append(out, r)
	}
	return out
}

// SymlinksIncludeRule is the one built-in included directory: the mirrored
// storage tree of `ws symlink` keeps host names (.gitconfig, .ssh/, .config/), and
// the built-in `-:.*` exclude would drop all of them. It sits where the user's
// included directories sit, so a user's ignored path still wins. It is not stored
// in ws.json and cannot be suppressed.
const SymlinksIncludeRule = "+g:symlinks/**"

// builtinInclude is SymlinksIncludeRule as a Rule, tagged SourceBuiltin.
func builtinInclude() Rule {
	return Rule{Raw: SymlinksIncludeRule, Include: true, Glob: true, Pattern: "symlinks/**", Source: SourceBuiltin}
}

// userRulesOf converts entries to rules, skipping blank patterns.
func userRulesOf(entries []RuleEntry, include bool) []Rule {
	var out []Rule
	for _, e := range entries {
		p := strings.TrimSpace(e.Pattern)
		if p == "" {
			continue
		}
		r := userPatternToRule(p, include)
		r.Source = SourceUser
		out = append(out, r)
	}
	return out
}

// BuildEngine creates an Engine from built-in defaults + user rules, in the
// order MEGA reads .megaignore (the last matching rule decides):
//  1. built-in excludes (minus suppress_defaults)
//  2. the built-in included directory symlinks/** and the user's included
//     directories (include)
//  3. user excludes (ignore_rules.exclude): last, so `ignore add` always wins
func BuildEngine(userRules UserRules) *Engine {
	var rules []Rule
	rules = append(rules, builtinExcludes(userRules)...)
	rules = append(rules, builtinInclude())
	rules = append(rules, userRulesOf(userRules.Include, true)...)
	rules = append(rules, userRulesOf(userRules.Exclude, false)...)
	return &Engine{Rules: rules}
}

// userPatternToRule converts a user pattern string to a Rule.
// Patterns containing * or ** are treated as glob rules.
func userPatternToRule(pattern string, include bool) Rule {
	prefix := "-:"
	if include {
		prefix = "+:"
	}

	isGlob := strings.Contains(pattern, "*")
	if isGlob {
		prefix = "-g:"
		if include {
			prefix = "+g:"
		}
	}

	return Rule{
		Raw:     prefix + pattern,
		Include: include,
		Glob:    isGlob,
		Pattern: pattern,
	}
}

// GenerateMegaignore produces the .megaignore file content from defaults + user
// rules, in the same order BuildEngine evaluates them.
func GenerateMegaignore(userRules UserRules) string {
	var sb strings.Builder

	sb.WriteString("# Generated by ws — do not edit manually.\n")
	sb.WriteString("# Edit the rules: ws ignore edit\n")
	sb.WriteString("# Source: ws.json (ignore_rules)\n")
	sb.WriteString("\n")

	sb.WriteString("# Built-in rules\n")
	for _, r := range builtinExcludes(userRules) {
		sb.WriteString(r.Raw + "\n")
	}

	sb.WriteString("\n# Built-in included directory (the ws symlink storage tree)\n")
	sb.WriteString(SymlinksIncludeRule + "\n")

	if len(userRules.Include) > 0 {
		sb.WriteString("\n# Included directories (ws.json include)\n")
		writeEntries(&sb, userRules.Include, true)
	}

	// Ignored paths come last so they win over every included directory.
	if len(userRules.Exclude) > 0 {
		sb.WriteString("\n# Ignored paths (ws ignore add)\n")
		writeEntries(&sb, userRules.Exclude, false)
	}

	sb.WriteString("\n# Never sync symlinks (s = symlink target)\n")
	sb.WriteString("-s:*\n")

	return sb.String()
}

func writeEntries(sb *strings.Builder, entries []RuleEntry, include bool) {
	for _, e := range entries {
		p := strings.TrimSpace(e.Pattern)
		if p == "" {
			continue
		}
		if e.Note != "" {
			sb.WriteString("# " + strings.ReplaceAll(e.Note, "\n", " ") + "\n")
		}
		sb.WriteString(userPatternToRule(p, include).Raw + "\n")
	}
}

// WriteMegaignore generates and writes the .megaignore file from user rules.
func WriteMegaignore(megaignorePath string, userRules UserRules) error {
	content := GenerateMegaignore(userRules)
	return os.WriteFile(megaignorePath, []byte(content), 0o644)
}

// Stale reports whether the file at megaignorePath differs from what the rules
// generate. A missing file is stale.
func Stale(megaignorePath string, userRules UserRules) (bool, error) {
	data, err := os.ReadFile(megaignorePath)
	if err != nil {
		if os.IsNotExist(err) {
			return true, nil
		}
		return false, err
	}
	return string(data) != GenerateMegaignore(userRules), nil
}

// DefaultRuleStats returns counts of default and user rules for display.
type RuleStats struct {
	DefaultExclude     int
	UserExclude        int
	UserInclude        int
	SuppressedDefaults int
	Total              int
}

func GetRuleStats(userRules UserRules) RuleStats {
	suppD := 0
	for _, s := range userRules.SuppressDefaults {
		for _, dr := range defaultExcludeRules {
			if dr.Pattern == s {
				suppD++
				break
			}
		}
	}
	stats := RuleStats{
		DefaultExclude:     len(defaultExcludeRules) - suppD,
		UserExclude:        len(userRules.Exclude),
		UserInclude:        len(userRules.Include),
		SuppressedDefaults: suppD,
	}
	stats.Total = stats.DefaultExclude + stats.UserExclude + stats.UserInclude
	return stats
}

// ExcludeEngine builds an engine from exclude patterns alone (ignore_rules
// syntax), for extra lists such as sync.exclude. A path it does not match
// evaluates as included.
func ExcludeEngine(entries []RuleEntry) *Engine {
	return &Engine{Rules: userRulesOf(entries, false)}
}
