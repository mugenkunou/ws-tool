// Sentinel markers for idempotent enable/disable.
const (
	completionMarkerStart = "# >>> ws shell completion >>>"
	completionMarkerEnd   = "# <<< ws shell completion <<<"
)

func runCompletion(args []string, globals globalFlags, stdin io.Reader, stdout, stderr io.Writer) int {
	if len(args) == 0 {
		fmt.Fprintln(stderr, "usage: ws completion <bash|zsh|fish|enable|disable>")
		return 1
	}
	action := strings.ToLower(strings.TrimSpace(args[0]))
	switch action {
	case "bash", "zsh", "fish":
		script := completionScript(action)
		if globals.json {
			return writeJSON(stdout, stderr, "completion."+action, map[string]any{
				"shell":  action,
				"script": script,
			})
		}
		fmt.Fprintln(stdout, script)
		return 0
	case "enable":
		return runCompletionEnable(args[1:], globals, stdin, stdout, stderr)
	case "disable":
		return runCompletionDisable(args[1:], globals, stdin, stdout, stderr)
	default:
		fmt.Fprintf(stderr, "unknown command: completion %s\n", args[0])
		fmt.Fprintln(stderr, "usage: ws completion <bash|zsh|fish|enable|disable>")
		return 1
	}
}

// ── Shell scripts (thin __complete dispatchers) ────────────────────

func completionScript(shell string) string {
	switch shell {
	case "bash":
		return bashCompletionScript()
	case "zsh":
		return zshCompletionScript()
	case "fish":
		return fishCompletionScript()
	default:
		return ""
	}
}

func bashCompletionScript() string {
	return `# ws bash completion — generated by ws completion bash
_ws_completions() {
    local IFS=$'\n'
    local out line directive
    local -a comps=()

    # Call the binary to resolve completions for the current word list.
    out=$(ws __complete "${COMP_WORDS[@]:1}" 2>/dev/null)

    # Parse output: each line is a completion, last line is :<directive>.
    while IFS= read -r line; do
        if [[ "$line" == :* ]]; then
            directive="${line#:}"
        else
            [[ -n "$line" ]] && comps+=("$line")
        fi
    done <<< "$out"

    # If no explicit completions and directive allows files, let bash
    # fall through to default file completion.
    if (( ${#comps[@]} == 0 )); then
        if (( directive & 4 )); then
            # NoFileComp — nothing to offer.
            COMPREPLY=()
        fi
        return 0
    fi

    COMPREPLY=("${comps[@]}")

    # Apply directives.
    if (( directive & 2 )); then
        compopt -o nospace
    fi
    if (( directive & 4 )); then
        compopt +o default
    fi

    return 0
}
complete -o default -F _ws_completions ws

# wsopen — open a scratch directory in VS Code and cd to it.
# Usage: wsopen [name]
wsopen() {
    local path
    path=$(ws scratch open --print-path "$@") || return $?
    cd "$path"
}`
}

func zshCompletionScript() string {
	return `#compdef ws
# ws zsh completion — generated by ws completion zsh

_ws() {
    local -a completions
    local directive line

    # Build the word list from the current command line.
    # words[1] is "ws", words[2..] are the arguments.
    local -a ws_args=("${words[@]:1}")

    # Call the binary.
    local out
    out=$(ws __complete "${ws_args[@]}" 2>/dev/null)

    # Parse output.
    while IFS= read -r line; do
        if [[ "$line" == :* ]]; then
            directive="${line#:}"
        else
            [[ -n "$line" ]] && completions+=("$line")
        fi
    done <<< "$out"

    if (( ${#completions[@]} == 0 )); then
        if (( directive & 4 )); then
            _message 'no completions'
        else
            _files
        fi
        return
    fi

    compadd -- "${completions[@]}"

    # NoSpace
    if (( directive & 2 )); then
        compstate[insert]=unambiguous
    fi
}

compdef _ws ws

# wsopen — open a scratch directory in VS Code and cd to it.
# Usage: wsopen [name]
wsopen() {
    local path
    path=$(ws scratch open --print-path "$@") || return $?
    cd "$path"
}`
}

func fishCompletionScript() string {
	return `# ws fish completion — generated by ws completion fish

function __ws_complete
    set -l tokens (commandline -opc)
    set -l current (commandline -ct)

    # Drop the command name "ws".
    set -e tokens[1]

    set -l out (ws __complete $tokens $current 2>/dev/null)

    # Last line is :<directive>.
    set -l directive 0
    for line in $out
        if string match -qr '^:[0-9]+$' -- $line
            set directive (string sub -s 2 -- $line)
        else
            echo $line
        end
    end

    # Return 1 if NoFileComp so fish does not add file completions.
    if test (math "$directive & 4") -ne 0
        return 1
    end
    return 0
end

complete -c ws -f -a '(__ws_complete)'

# wsopen — open a scratch directory in VS Code and cd to it.
# Usage: wsopen [name]
function wsopen
    set -l path (ws scratch open --print-path $argv)
    or return $status
    cd $path
end`
}

// ── Enable / disable ───────────────────────────────────────────────

func runCompletionEnable(args []string, globals globalFlags, stdin io.Reader, stdout, stderr io.Writer) int {
	shell, err := parseCompletionFlags(args, &globals)
	if err != nil {
		fmt.Fprintln(stderr, err.Error())
		return 1
	}
	rcPath, line, err := completionRCInfo(shell)
	if err != nil {
		fmt.Fprintln(stderr, err.Error())
		return 1
	}

	content, _ := os.ReadFile(rcPath) // a missing rc file is created
	block := fmt.Sprintf("%s\n%s\n%s\n", completionMarkerStart, line, completionMarkerEnd)
	updated := withCompletionBlock(string(content), block)

	pl := Plan{Command: "completion.enable"}
	if updated != string(content) {
		pl.Actions = append(pl.Actions, Action{
			ID:          "completion-enable",
			Description: fmt.Sprintf("Load ws completion from %s", rcPath),
			Execute: func() error {
				if err := os.MkdirAll(filepath.Dir(rcPath), 0o755); err != nil {
					return err
				}
				return os.WriteFile(rcPath, []byte(updated), 0o644)
			},
		})
	}
	res := RunPlan(pl, stdin, stdout, globals)

	if globals.json {
		return writeJSONDryRun(stdout, stderr, "completion.enable", globals.dryRun, map[string]any{
			"shell": shell, "path": rcPath, "actions": actionsOrEmpty(res),
		})
	}
	out := textOut(globals, stdout)
	switch {
	case len(pl.Actions) == 0:
		fmt.Fprintf(out, "Completion is already enabled in %s\n", rcPath)
	case res.WasExecuted("completion-enable"):
		fmt.Fprintf(out, "Completion enabled in %s\n", rcPath)
		fmt.Fprintf(out, "Run `source %s` or open a new terminal to activate.\n", rcPath)
	}
	return res.ExitCode()
}

func runCompletionDisable(args []string, globals globalFlags, stdin io.Reader, stdout, stderr io.Writer) int {
	shell, err := parseCompletionFlags(args, &globals)
	if err != nil {
		fmt.Fprintln(stderr, err.Error())
		return 1
	}
	rcPath, _, err := completionRCInfo(shell)
	if err != nil {
		fmt.Fprintln(stderr, err.Error())
		return 1
	}

	content, _ := os.ReadFile(rcPath)
	cleaned := removeMarkerBlock(string(content))

	pl := Plan{Command: "completion.disable"}
	if containsCompletionMarker(string(content)) {
		pl.Actions = append(pl.Actions, Action{
			ID:          "completion-disable",
			Description: fmt.Sprintf("Remove ws completion from %s", rcPath),
			Execute:     func() error { return os.WriteFile(rcPath, []byte(cleaned), 0o644) },
		})
	}
	res := RunPlan(pl, stdin, stdout, globals)

	if globals.json {
		return writeJSONDryRun(stdout, stderr, "completion.disable", globals.dryRun, map[string]any{
			"shell": shell, "path": rcPath, "actions": actionsOrEmpty(res),
		})
	}
	out := textOut(globals, stdout)
	switch {
	case len(pl.Actions) == 0:
		fmt.Fprintf(out, "Completion is not enabled in %s\n", rcPath)
	case res.WasExecuted("completion-disable"):
		fmt.Fprintf(out, "Completion removed from %s\n", rcPath)
	}
	return res.ExitCode()
}

func actionsOrEmpty(res PlanResult) []ActionStatus {
	if res.Actions == nil {
		return []ActionStatus{}
	}
	return res.Actions
}

// withCompletionBlock returns text with the marked block set to block: an
// existing block (current or older line) is replaced in place, unmarked lines
// that load ws completion are removed, and a missing block is appended.
func withCompletionBlock(text, block string) string {
	if containsCompletionMarker(text) {
		start := strings.Index(text, completionMarkerStart)
		end := strings.Index(text, completionMarkerEnd)
		if end > start {
			end += len(completionMarkerEnd)
			if end < len(text) && text[end] == '\n' {
				end++
			}
			return removeStaleCompletionLines(text[:start]) + block + removeStaleCompletionLines(text[end:])
		}
	}
	cleaned := removeStaleCompletionLines(text)
	if cleaned != "" && !strings.HasSuffix(cleaned, "\n") {
		cleaned += "\n"
	}
	if cleaned != "" {
		cleaned += "\n"
	}
	return cleaned + block
}

// ── Helpers ────────────────────────────────────────────────────────

// parseCompletionFlags reads --shell (default: the base name of $SHELL). Any
// shell but bash, zsh or fish is an error.
func parseCompletionFlags(args []string, globals *globalFlags) (string, error) {
	fs := flag.NewFlagSet("completion", flag.ContinueOnError)
	fs.SetOutput(io.Discard)
	shell := fs.String("shell", "", "bash, zsh or fish")
	registerGlobalFlags(fs, globals)
	if err := parseInterspersed(fs, args); err != nil {
		return "", err
	}
	if fs.NArg() > 0 {
		return "", fmt.Errorf("unexpected argument %q", fs.Arg(0))
	}
	sh := strings.ToLower(strings.TrimSpace(*shell))
	if sh == "" {
		sh = detectShell()
	}
	if sh != "bash" && sh != "zsh" && sh != "fish" {
		return "", fmt.Errorf("unsupported shell %q (use --shell bash|zsh|fish)", sh)
	}
	return sh, nil
}

// detectShell resolves the current shell from $SHELL.
func detectShell() string {
	s := os.Getenv("SHELL")
	if s == "" {
		return "bash" // safe default on Linux
	}
	base := filepath.Base(s)
	switch base {
	case "bash", "zsh", "fish":
		return base
	default:
		return base
	}
}

// completionRCInfo returns the rc file path and the eval line for a given shell.
func completionRCInfo(shell string) (rcPath, evalLine string, err error) {
	home, err := os.UserHomeDir()
	if err != nil {
		return "", "", err
	}
	switch shell {
	case "bash":
		return filepath.Join(home, ".bashrc"), `eval "$(ws completion bash)"`, nil
	case "zsh":
		return filepath.Join(home, ".zshrc"), `eval "$(ws completion zsh)"`, nil
	case "fish":
		confDir := os.Getenv("XDG_CONFIG_HOME")
		if confDir == "" {
			confDir = filepath.Join(home, ".config")
		}
		return filepath.Join(confDir, "fish", "conf.d", "ws.fish"), "ws completion fish | source", nil
	default:
		return "", "", fmt.Errorf("unsupported shell: %s", shell)
	}
}

// containsCompletionMarker returns true if the text contains our sentinel markers.
func containsCompletionMarker(text string) bool {
	return strings.Contains(text, completionMarkerStart)
}

// removeMarkerBlock removes everything between (and including) the sentinel
// markers. Preserves the rest of the file exactly.
func removeMarkerBlock(text string) string {
	start := strings.Index(text, completionMarkerStart)
	if start < 0 {
		return text
	}
	end := strings.Index(text, completionMarkerEnd)
	if end < 0 {
		return text
	}
	end += len(completionMarkerEnd)
	// Also consume the trailing newline after the end marker.
	if end < len(text) && text[end] == '\n' {
		end++
	}
	// Also consume a leading newline before the start marker.
	if start > 0 && text[start-1] == '\n' {
		start--
	}
	return text[:start] + text[end:]
}

// removeStaleCompletionLines removes any pre-existing ws completion lines
// that were manually added before the sentinel system existed.
// This handles the duplicate-entry problem.
func removeStaleCompletionLines(text string) string {
	lines := strings.Split(text, "\n")
	var cleaned []string
	for _, line := range lines {
		trimmed := strings.TrimSpace(line)
		if isStaleCompletionLine(trimmed) {
			continue
		}
		cleaned = append(cleaned, line)
	}
	return strings.Join(cleaned, "\n")
}

// isStaleCompletionLine detects old-style manual completion setup lines.
func isStaleCompletionLine(line string) bool {
	// Common patterns people might have added manually:
	//   eval "$(ws completions bash)"
	//   source <(ws completions bash)
	//   ws completions bash | source
	if strings.Contains(line, "ws completions") || strings.Contains(line, "ws completion ") || strings.Contains(line, "ws-completions") {
		// Don't match comment lines (they're harmless).
		if strings.HasPrefix(line, "#") {
			return false
		}
		return true
	}
	return false
}
