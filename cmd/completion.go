func runCompletion(args []string, globals globalFlags, stdin io.Reader, stdout, stderr io.Writer) int {
	if len(args) == 0 {
		fmt.Fprintln(stderr, "usage: ws completion <bash|zsh|fish|enable|disable>")
		return 1
	}
	action := strings.ToLower(strings.TrimSpace(args[0]))
	switch action {
	case "bash", "zsh", "fish":
		script := completionScript(action)
		if globals.json {
			return writeJSON(stdout, stderr, "completion."+action, map[string]any{
				"shell":  action,
				"script": script,
			})
		}
		fmt.Fprintln(stdout, script)
		return 0
	case "enable":
		return runCompletionEnable(args[1:], globals, stdin, stdout, stderr)
	case "disable":
		return runCompletionDisable(args[1:], globals, stdin, stdout, stderr)
	default:
		fmt.Fprintf(stderr, "unknown command: completion %s\n", args[0])
		fmt.Fprintln(stderr, "usage: ws completion <bash|zsh|fish|enable|disable>")
		return 1
	}
}

// ── Shell scripts (thin __complete dispatchers) ────────────────────

func completionScript(shell string) string {
	switch shell {
	case "bash":
		return bashCompletionScript()
	case "zsh":
		return zshCompletionScript()
	case "fish":
		return fishCompletionScript()
	default:
		return ""
	}
}

func bashCompletionScript() string {
	return `# ws bash completion — generated by ws completion bash
_ws_completions() {
    local IFS=$'\n'
    local out line directive
    local -a comps=()

    # Call the binary to resolve completions for the current word list.
    out=$(ws __complete "${COMP_WORDS[@]:1}" 2>/dev/null)

    # Parse output: each line is a completion, last line is :<directive>.
    while IFS= read -r line; do
        if [[ "$line" == :* ]]; then
            directive="${line#:}"
        else
            [[ -n "$line" ]] && comps+=("$line")
        fi
    done <<< "$out"

    # If no explicit completions and directive allows files, let bash
    # fall through to default file completion.
    if (( ${#comps[@]} == 0 )); then
        if (( directive & 4 )); then
            # NoFileComp — nothing to offer.
            COMPREPLY=()
        fi
        return 0
    fi

    COMPREPLY=("${comps[@]}")

    # Apply directives.
    if (( directive & 2 )); then
        compopt -o nospace
    fi
    if (( directive & 4 )); then
        compopt +o default
    fi

    return 0
}
complete -o default -F _ws_completions ws

# wsopen — open a scratch directory in VS Code and cd to it.
# Usage: wsopen [name]
wsopen() {
    local path
    path=$(ws scratch open --print-path "$@") || return $?
    cd "$path"
}`
}

func zshCompletionScript() string {
	return `#compdef ws
# ws zsh completion — generated by ws completion zsh

_ws() {
    local -a completions
    local directive line

    # Build the word list from the current command line.
    # words[1] is "ws", words[2..] are the arguments.
    local -a ws_args=("${words[@]:1}")

    # Call the binary.
    local out
    out=$(ws __complete "${ws_args[@]}" 2>/dev/null)

    # Parse output.
    while IFS= read -r line; do
        if [[ "$line" == :* ]]; then
            directive="${line#:}"
        else
            [[ -n "$line" ]] && completions+=("$line")
        fi
    done <<< "$out"

    if (( ${#completions[@]} == 0 )); then
        if (( directive & 4 )); then
            _message 'no completions'
        else
            _files
        fi
        return
    fi

    compadd -- "${completions[@]}"

    # NoSpace
    if (( directive & 2 )); then
        compstate[insert]=unambiguous
    fi
}

compdef _ws ws

# wsopen — open a scratch directory in VS Code and cd to it.
# Usage: wsopen [name]
wsopen() {
    local path
    path=$(ws scratch open --print-path "$@") || return $?
    cd "$path"
}`
}

func fishCompletionScript() string {
	return `# ws fish completion — generated by ws completion fish

function __ws_complete
    set -l tokens (commandline -opc)
    set -l current (commandline -ct)

    # Drop the command name "ws".
    set -e tokens[1]

    set -l out (ws __complete $tokens $current 2>/dev/null)

    # Last line is :<directive>.
    set -l directive 0
    for line in $out
        if string match -qr '^:[0-9]+$' -- $line
            set directive (string sub -s 2 -- $line)
        else
            echo $line
        end
    end

    # Return 1 if NoFileComp so fish does not add file completions.
    if test (math "$directive & 4") -ne 0
        return 1
    end
    return 0
end

complete -c ws -f -a '(__ws_complete)'

# wsopen — open a scratch directory in VS Code and cd to it.
# Usage: wsopen [name]
function wsopen
    set -l path (ws scratch open --print-path $argv)
    or return $status
    cd $path
end`
}

// ── Enable / disable ───────────────────────────────────────────────

func runCompletionEnable(args []string, globals globalFlags, stdin io.Reader, stdout, stderr io.Writer) int {
	shell, err := parseCompletionFlags(args, &globals)
	if err != nil {
		fmt.Fprintln(stderr, err.Error())
		return 1
	}
	rcPath, actions, err := shellcomp.EnablePlan(shell)
	if err != nil {
		fmt.Fprintln(stderr, err.Error())
		return 1
	}

	pl := Plan{Command: "completion.enable", Actions: actions}
	res := RunPlan(pl, stdin, stdout, globals)

	if globals.json {
		return writeJSONDryRun(stdout, stderr, "completion.enable", globals.dryRun, map[string]any{
			"shell": shell, "path": rcPath, "actions": actionsOrEmpty(res),
		})
	}
	out := textOut(globals, stdout)
	switch {
	case len(pl.Actions) == 0:
		fmt.Fprintf(out, "Completion is already enabled in %s\n", rcPath)
	case res.WasExecuted(shellcomp.EnableID):
		fmt.Fprintf(out, "Completion enabled in %s\n", rcPath)
		fmt.Fprintf(out, "Run `source %s` or open a new terminal to activate.\n", rcPath)
	}
	return res.ExitCode()
}

func runCompletionDisable(args []string, globals globalFlags, stdin io.Reader, stdout, stderr io.Writer) int {
	shell, err := parseCompletionFlags(args, &globals)
	if err != nil {
		fmt.Fprintln(stderr, err.Error())
		return 1
	}
	rcPath, actions, err := shellcomp.DisablePlan(shell)
	if err != nil {
		fmt.Fprintln(stderr, err.Error())
		return 1
	}

	pl := Plan{Command: "completion.disable", Actions: actions}
	res := RunPlan(pl, stdin, stdout, globals)

	if globals.json {
		return writeJSONDryRun(stdout, stderr, "completion.disable", globals.dryRun, map[string]any{
			"shell": shell, "path": rcPath, "actions": actionsOrEmpty(res),
		})
	}
	out := textOut(globals, stdout)
	switch {
	case len(pl.Actions) == 0:
		fmt.Fprintf(out, "Completion is not enabled in %s\n", rcPath)
	case res.WasExecuted(shellcomp.DisableID):
		fmt.Fprintf(out, "Completion removed from %s\n", rcPath)
	}
	return res.ExitCode()
}

func actionsOrEmpty(res PlanResult) []ActionStatus {
	if res.Actions == nil {
		return []ActionStatus{}
	}
	return res.Actions
}

// ── Helpers ────────────────────────────────────────────────────────

// parseCompletionFlags reads --shell (default: the base name of $SHELL). Any
// shell but bash, zsh or fish is an error.
func parseCompletionFlags(args []string, globals *globalFlags) (string, error) {
	fs := flag.NewFlagSet("completion", flag.ContinueOnError)
	fs.SetOutput(io.Discard)
	shell := fs.String("shell", "", "bash, zsh or fish")
	registerGlobalFlags(fs, globals)
	if err := parseInterspersed(fs, args); err != nil {
		return "", err
	}
	if fs.NArg() > 0 {
		return "", fmt.Errorf("unexpected argument %q", fs.Arg(0))
	}
	return shellcomp.Resolve(*shell)
}
